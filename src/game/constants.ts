/**
 * 机台几何与物理常量。
 *
 * 坐标系：x 左右，y 上下，z 纵深（+z 朝向玩家 / 出币口）。单位统一为米。
 *
 * 结构分两层，和真实推币机一致：
 *   · 上层 = 推板顶面。币从落币口掉在它上面，被「台面输送」推着向前，走到前缘掉下去。
 *   · 下层 = 币床。币堆在这里，由推板前表面（推币面）往复推向前沿得分线。
 * 推板是一整块运动学刚体：顶面是上层，前表面是推币面，一起沿 z 往复。
 */

